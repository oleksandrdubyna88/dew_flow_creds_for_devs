/**
 * The prompt-site ledger (parent §7; the audit of 2026-11-06, 172 sites, by an AST walk and by reading): every place this extension can
 * put a question on a person's screen, with what may reach it. `promptSites.test.ts` holds the table EXACT in both directions, so a new
 * site fails until it is classed here and a row for a site that is gone fails until it is removed.
 *
 * <p>Classes. `before-allow`: the consent dialog itself. `after-allow`: a prompt an action's own code can raise after the person's Allow;
 * it keeps the one dialog place, so every action it names must carry the follow-up flag on its real factory. `detached`: one that is not
 * awaited and that no flag can cover. `gated`: reachable by reference but stopped by a run-time condition, said in `reason`. `person-only`:
 * no broker path reaches it, which the test's caller walk checks. A class is a claim about the code and is the review's to judge: the
 * table proves that a new site gets classed, not that its class is right.</p>
 *
 * <p>Not a test file: the runner is pointed at `*.test.js` only.</p>
 */

